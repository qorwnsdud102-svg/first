def load(p):
    s = open(p, encoding="utf-8", newline="").read()
    return s, ("\r\n" if s.count("\r\n") * 2 > s.count("\n") else "\n")


def save(p, s):
    open(p, "w", encoding="utf-8", newline="").write(s)


def edit(p, pairs):
    s, nl = load(p)
    for a, b in pairs:
        a2, b2 = a.replace("\n", nl), b.replace("\n", nl)
        assert s.count(a2) == 1, (p, a[:60], s.count(a2))
        s = s.replace(a2, b2)
    save(p, s)


def banner(p, text):
    """frontmatter 뒤(없으면 맨 위)에 대체 표시 한 줄."""
    s, nl = load(p)
    if "⚠️ 2026-10-14 정리" in s:
        return
    line = f"> ⚠️ 2026-10-14 정리: {text} 현행 입구는 `기획-시스템/{NOW}`." + nl + nl
    if s.startswith("---"):
        end = s.index(nl + "---", 3) + len(nl + "---") + len(nl)
        s = s[:end] + nl + line + s[end:]
    else:
        s = line + s
    save(p, s)


