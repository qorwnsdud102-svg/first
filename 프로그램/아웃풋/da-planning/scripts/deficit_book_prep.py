BLIND_AD = re.compile(r'\n\n(?:[^\n]{1,90}\n){1,3}(?=좋아요\n(?:\d+|좋아요) ?\n댓글)')   # 좋아요 0개면 숫자 대신 '좋아요'가 한 번 더 나온다
def strip_ads(t):
    # 10-19 M14: 블라인드 글 끝 '좋아요' 바로 앞 1~3줄은 회사 태그·광고('플란치과, 임플란트 가격 할인'·'퓨어그램 모공 탄력 세럼')라 뺀다 — 비싸다 칸·대안 이름 셈을 부풀렸다
    return BLIND_AD.sub('\n\n', t) if '\n좋아요\n' in t else t

def drop_noise(rows, name):
    pat, pos = NEG.get(name), POS.get(name)
    for r in rows:
        if r.get('text'): r['text'] = strip_ads(r['text'])
    tp = THREAD_POS.get(name)
    in_tp = (lambda r: True) if tp and tp[0] == '*' else (lambda r: r.get('source') in (tp[0] if isinstance(tp[0], tuple) else (tp[0],))) if tp else (lambda r: False)
    if tp:
        hl = tp[2] if len(tp) > 2 else 150
        heads = {r.get('url'): r.get('text', '')[:hl] for r in rows if in_tp(r) and r.get('type') == '글'}
        rows = [r for r in rows if not in_tp(r) or re.search(tp[1], r.get('text', '')) or re.search(tp[1], heads.get(r.get('url'), ''))]
    tn = THREAD_NEG.get(name)
    if tn:
        in_tn = lambda r: tn[0] == '*' or r.get('source') in tn[0]
        nheads = {r.get('url'): r.get('text', '')[:tn[2]] for r in rows if in_tn(r) and r.get('type') == '글'}
        rows = [r for r in rows if not (in_tn(r) and re.search(tn[1], nheads.get(r.get('url'), '')))]
    rows = [r for r in rows if not (pat and re.search(pat, r.get('text', ''))) and not (pos and not in_tp(r) and not re.search(pos, r.get('text', '')))
            and not re.search(NEG_ALL, r.get('text', ''))
            and not ('지식' in str(r.get('source', '')) and KIN_PROMO.search(r.get('text', '')))]
    # 10-19 M13: 복붙 글(앞 80자가 같은 글)은 하나만, 6,000자 넘는 목록형 글('미용법 50가지')은 뺀다 — 발뒤꿈치각질 타겟 발화의 24%가 복붙이었다
    # 10-19 M16: 제목만 바꾼 복붙(은행잎추출물 '기억력을 높여주는 15가지 생활 습관' 10번)은 앞 80자가 달라 빠져나갔다 — 40자 넘는 문장 5개 중 2개가 이미 본 글과 같으면 복붙으로 본다
    seen, sents, out = set(), set(), []
    for r in rows:
        t = r.get('text', '')
        if len(t) > 6000: continue
        k = re.sub(r'\s+', '', t)[:80]
        if len(k) >= 30 and k in seen: continue
        ls = [x for x in (re.sub(r'\s+', '', s) for s in re.split(r'[.!?\n]', t)) if len(x) >= 40][:5]
        if sum(x in sents for x in ls) >= 2: continue
        seen.add(k); sents.update(ls); out.append(r)
    return out

